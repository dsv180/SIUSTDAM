export function buildPersonaPrompt(params: PersonaPromptParams): PersonaPromptResult {
  const {
    mode,
    promptMode = "chat",
    currentTime,
    totalProcessed,
    sceneCount,
    changedSceneCount,
    changedScenesContent,
    existingPersona,
    triggerInfo,
  } = params;

  const isCodeMode = promptMode === "code";
  const targetFile = "persona.md";
  const modeLabel = mode === "first" ? "🆕 первичная генерация" : "🔄 итерационное обновление";

  const triggerSection = triggerInfo
    ? `\n### Информация о триггере\n${triggerInfo}\n`
    : "";

  const existingPersonaSection = existingPersona
    ? isCodeMode
      ? `\n## 📄 Текущая Team Operating Doctrine (предзагружена инженерной частью)\n\n` +
        `*Ниже — полное текущее содержимое Team Operating Doctrine из persona.md (${existingPersona.length} символов). После обновления — сжать до 1200 слов:*\n\n` +
        `\`\`\`markdown\n${existingPersona}\n\`\`\`\n\n---\n`
      : `\n## 📄 Текущая Persona (предзагружена инженерной частью)\n\n` +
        `*Ниже — полное текущее содержимое persona.md (${existingPersona.length} символов); после обновления — держи в пределах 2000 символов:*\n\n` +
        `\`\`\`markdown\n${existingPersona}\n\`\`\`\n\n---\n`
    : "";

  const iterationGuide = mode === "incremental"
    ? isCodeMode
      ? `\n## 🔄 Гайд по итерационному решению\n\n` +
        `Перед изменёнными сценами решай самостоятельно: усилить (подтверждение имеющихся принципов) / дополнить (новые универсальные SOP, запреты, логика суждений или правила агентов) / исправить (старый принцип обновлён) / реструктурировать (стало длиннее, рыхлее, проектнее) / не менять (только статусы проектов или низкоуровневые факты).\n`
      : `\n## 🔄 Гайд по итерационному решению\n\n` +
        `Перед изменёнными сценами решай самостоятельно: усилить (подтверждение имеющихся инсайтов) / дополнить (новые измерения) / исправить (противоречия) / реструктурировать (структурная перестройка) / не менять (нет полезных дополнений).\n`
    : "";

  const userPrompt = `**Язык вывода**: \`${targetFile}\` — на доминирующем языке изменённых сцен ниже.

**⏰ Время обновления**: ${currentTime}
**Режим**: ${modeLabel}
${triggerSection}
## 📊 Статистика
- **Всего памяток**: ${totalProcessed}
- **Всего сцен**: ${sceneCount}
- **Изменённые сцены**: ${changedSceneCount} (с прошлого обновления)

---
${changedScenesContent}

${existingPersonaSection}
${iterationGuide}`;

  return {
    systemPrompt: isCodeMode ? TEAM_MEMORY_SYSTEM_PROMPT : PERSONA_SYSTEM_PROMPT,
    userPrompt,
  };
}
